import re
from datetime import datetime
from pathlib import Path
from xml.sax.saxutils import escape

from docx import Document
from docx.shared import Inches, Pt
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    KeepTogether,
)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
EXPORTS_DIR = PROJECT_ROOT / "exports"


def safe_session_name(session_id: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", session_id).strip("_")
    return (cleaned or "conversation")[:70]


def export_paths(conversation):
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    base = f"conversation_{conversation.id}_{safe_session_name(conversation.session_id)}"
    return EXPORTS_DIR / f"{base}.docx", EXPORTS_DIR / f"{base}.pdf"


def _transcript_sections(conversation):
    caller_text = getattr(conversation, "caller_text", "") or ""
    agent_text = getattr(conversation, "agent_text", "") or ""

    # Prefer the complete chronological dialogue when it has been saved.
    for candidate in (agent_text, caller_text):
        transcript = candidate.strip()
        if (
            transcript.startswith("USER:")
            and "ASSISTANT:" in transcript
        ):
            return [("Transcript", transcript)]

    # Older records may contain only separate caller/assistant text.
    # Their original turn order cannot reliably be reconstructed.
    return [
        ("USER", caller_text or "No caller transcript was recorded."),
        ("ASSISTANT", agent_text or "No assistant transcript was recorded."),
    ]
def create_conversation_exports(conversation):
    docx_path, pdf_path = export_paths(conversation)
    created_at = conversation.created_at
    timestamp = (
        created_at.strftime("%Y-%m-%d %H:%M:%S")
        if created_at
        else datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    )

    # Create the editable Word document.
    document = Document()
    section = document.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)

    title = document.add_heading("AI Voice Agent — Conversation Transcript", 0)
    title.alignment = 1

    document.add_paragraph(f"Conversation ID: {conversation.id}")
    document.add_paragraph(f"Session ID: {conversation.session_id}")
    document.add_paragraph(f"Saved at: {timestamp}")
    document.add_paragraph("")

    for speaker, text in _transcript_sections(conversation):
        document.add_heading(speaker, level=1)
        for line in text.splitlines() or [text]:
            document.add_paragraph(line)

    document.add_paragraph("")
    footer = section.footer.paragraphs[0]
    footer.text = "Generated by AI Voice Agent"
    document.save(docx_path)

    # Create the PDF transcript.
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="TranscriptTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        textColor=colors.HexColor("#283593"),
        spaceAfter=12,
    ))
    styles.add(ParagraphStyle(
        name="SpeakerHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#283593"),
        spaceBefore=12,
        spaceAfter=5,
    ))
    styles.add(ParagraphStyle(
        name="TranscriptBody",
        parent=styles["BodyText"],
        leading=15,
        spaceAfter=5,
        wordWrap="CJK",
    ))

    pdf = SimpleDocTemplate(
        str(pdf_path),
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"Conversation {conversation.id}",
        author="AI Voice Agent",
    )

    story = [
        Paragraph("AI Voice Agent — Conversation Transcript", styles["TranscriptTitle"]),
        Paragraph(f"<b>Conversation ID:</b> {conversation.id}", styles["BodyText"]),
        Paragraph(f"<b>Session ID:</b> {escape(conversation.session_id)}", styles["BodyText"]),
        Paragraph(f"<b>Saved at:</b> {escape(timestamp)}", styles["BodyText"]),
        Spacer(1, 10),
    ]

    for speaker, text in _transcript_sections(conversation):
        story.append(KeepTogether([
            Paragraph(escape(speaker), styles["SpeakerHeading"]),
            Paragraph(escape(text).replace("\n", "<br/>"), styles["TranscriptBody"]),
        ]))

    pdf.build(story)
    return docx_path, pdf_path
